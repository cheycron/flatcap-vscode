"""Role mapping for the Flatcap 2.0 VS Code themes.

Data only. Every color is a Flatcap role from src/theme.json, optionally with an alpha percentage:
    "role"      opaque role value
    "role/NN"   the role with NN percent alpha (overlays; effective contrast is checked by build.py)
    "shadow"    elevation.shadow.overlay (parsed from the core)
    "transparent"

Resolve meaning before the key: surfaces by function (canvas / surface / raised), feedback as
.fg + .bg pairs, syntax from syntax.*, series from data.*. Do not choose by hex proximity.
build.py rejects a key that is assigned twice.
"""

